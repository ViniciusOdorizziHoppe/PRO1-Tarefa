public class Equipe {
    
    private int identificadorDaEquipe;
    private String nome;
    private String tipo;
    private String status;

    public int getIdentificadorDaEquipe() {
        return identificadorDaEquipe;
    }

    public void setIdentificadorDaEquipe(int identificadorDaEquipe) {
        this.identificadorDaEquipe = identificadorDaEquipe;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getTipo() {
        return tipo;
    }

    public void setTipo(String tipo) {
        this.tipo = tipo;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }
    
    
}
